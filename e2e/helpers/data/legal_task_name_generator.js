import faker from 'faker'

export const getLegalTaskName = () => {
  const maxTaskNameLength = 50
  const name = `${getRandomItem(verbs)} ${getRandomItem(nouns)}${
    randomFlag() ? ' ' + getRandomItem(nouns) : ''
  }`

  return name.substring(0, maxTaskNameLength)
}

export const getLegalProjectName = () =>
  `${getRandomItem(projectWords)} ${Math.floor(Math.random() * 99)} ${
    faker.name.findName().split(' ')[1]
  }`.substring(0, 29)

const getRandomItem = targetArray =>
  targetArray && targetArray.length
    ? targetArray[Math.floor(Math.random() * targetArray.length)]
    : undefined

