import {
  enterPasscode,
  generateValidInvalidPasscodePairFromQRCode,
  loginViaUI,
} from '../../../../../helpers/login/mfa_helpers'
import VisitHelpers from '../../../../../helpers/matterprojects/visit_helpers'
import {
  createOrganisation,
  sysadminAddUserToOrganisation,
} from '../../../../../helpers/organisation/organisation_api_helper'
import {
  createUser,
  updateFTUE,
} from '../../../../../helpers/users/user_api_helper'

describe('login_with_mfa_verification.cy', () => {
  let testUser, generatedPasscode, invalidPasscode, organisation

  before(() => {
    createOrganisation('test', false)
      .then(_organisation => {
        organisation = _organisation.body
      })
      .then(() =>
        createUser(undefined, true, false, { roles: ['ROLE_ORG_ADMIN'] })
      )
      .then(createdUser => {
        testUser = createdUser
      })
      .then(() => sysadminAddUserToOrganisation(organisation, testUser))
      .then(() => {
        const visitHelpers = new VisitHelpers()
        cy.login(testUser.username)
        updateFTUE(testUser, { hasSeenOrgAdmin: true })
        cy.login(testUser.username)
        visitHelpers.visitHome()
        visitHelpers.visitOrgUsers()
        cy.wait(2000)
        cy.get('[data-test=settings]').click()
        cy.get('[data-test=mfa-panel-switch]').click()
        cy.get('[data-test=action-dialog-button]').click()
        cy.get('[data-test=accounts]').click()
        cy.get('[data-test=lock-switch-open]').click()
        cy.get('[data-test=action-dialog-button]').click()
        cy.clearUserSession()
        cy.visit('/#/login')
        cy.reload()
      })
  })

  describe('when logging in as a user with MFA enabled for the first time', () => {
    before(() => {
      loginViaUI(testUser.username)
    })

    it('should display a QR code', () => {
      cy.get('[data-test=mfa-register-qr] canvas').should('be.visible')
    })

    describe('when entering a passcode derived from the QR code', () => {
      before(() => {
        generateValidInvalidPasscodePairFromQRCode().then(passcodes => {
          generatedPasscode = passcodes[0]
          invalidPasscode = passcodes[1]
        })
      })

      describe('when entering an incorrect passcode', () => {
        before(() => {
          enterPasscode(invalidPasscode)
        })

        it('should display an error message', () => {
          cy.url().should('not.contain', '/#/home')
          cy.get('[data-test=validation-message]').should(
            'have.text',
            'Incorrect authentication code'
          )
        })
      })

      describe('when entering the correct passcode', () => {
        before(() => {
          enterPasscode(generatedPasscode)
        })

        it('should take the user to the home page', () => {
          cy.url().should('contain', '/#/home')
          cy.get('[data-test=validation-message]').should('not.exist')
        })
      })
    })
  })

  describe('when logging in again having previously completed a QR challenge', () => {
    before(() => {
      loginViaUI(testUser.username)
    })

    describe('the user is taken to the MFA validation screen (not to be confused with MFA registration screen)', () => {
      it('should display another message to guide user how to register MFA', () => {
        cy.get('[data-test="mfa-validate-message"]').contains(
          'Enter the six digit code generated by the authenticator app'
        )
      })

      it('should NOT display the QR code', () => {
        cy.get('[data-test="mfa-register-qr"]').should('not.exist')
      })

      describe('when entering an incorrect passcode', () => {
        before(() => {
          enterPasscode(invalidPasscode)
        })

        it('should display an error message', () => {
          cy.url().should('not.contain', '/#/home')
          cy.get('[data-test=validation-message]').should(
            'have.text',
            'Incorrect authentication code'
          )
        })
      })

      describe('when entering the correct passcode', () => {
        before(() => {
          enterPasscode(generatedPasscode)
        })

        it('should take the user to the home page', () => {
          cy.url().should('contain', '/#/home')
          cy.get('[data-test=validation-message]').should('not.exist')
        })
      })
    })
  })
})
